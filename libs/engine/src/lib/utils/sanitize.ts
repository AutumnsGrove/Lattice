/**
 * Sanitize HTML content to prevent XSS attacks
 * @param html - Raw HTML string to sanitize
 * @returns Sanitized HTML safe for rendering
 */
export function sanitizeHTML(html: string): string {
	if (!html || typeof html !== "string") {
		return "";
	}

	// On server, use server-safe sanitization with stricter tag list
	// Mirrors DOMPurify FORBID_TAGS: button, input, base, meta are forbidden here
	// but allowed in sanitizeMarkdown (for code block copy buttons)
	if (!BROWSER || !DOMPurify) {
		return sanitizeServerSafe(html, { forbidTags: ["button", "input", "base", "meta"] });
	}

	const config: Config = {
		FORBID_TAGS: [
			"script",
			"iframe",
			"object",
			"embed",
			"link",
			"style",
			"form",
			"input",
			"button",
			"base",
			"meta",
		],
		FORBID_ATTR: [
			"onerror",
			"onload",
			"onclick",
			"onmouseover",
			"onfocus",
			"onblur",
			"onchange",
			"onsubmit",
			"onmouseenter",
			"onmouseleave",
			"style",
		],
		ALLOWED_URI_REGEXP: /^(?:(?:https?|mailto|tel):|\/|#)/i,
		ALLOW_DATA_ATTR: false,
		KEEP_CONTENT: true,
		SAFE_FOR_TEMPLATES: true,
		RETURN_TRUSTED_TYPE: false,
	};

	return DOMPurify.sanitize(html, config) as string;
}

