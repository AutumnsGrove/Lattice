/**
 * Starts the server the browser journey drives: Aspen alone, plus the
 * Durable Objects worker it binds.
 *
 * Heartwood, Zephyr and Pulse are not needed — demo mode is the session, and the
 * journey reads and writes through Aspen's own bindings. Keeping the stack to
 * two configs is what makes this cheap enough to run on every PR.
 */
import { spawn } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const aspen = path.resolve(here, "..");
const repo = path.resolve(aspen, "../..");

const secret = process.env.DEMO_MODE_SECRET;
if (!secret) throw new Error("DEMO_MODE_SECRET must be set for the e2e server");

const child = spawn(
	"npx",
	[
		"wrangler",
		"dev",
		"-c",
		// Generated by prepare.mjs: same config, minus the AI binding that needs a
		// Cloudflare token CI does not have.
		"apps/aspen/wrangler.e2e.toml",
		"-c",
		"services/durable-objects/wrangler.local.toml",
		"--port",
		"5173",
		"--inspector-port",
		"9231",
		"--persist-to",
		path.join(aspen, ".e2e-state"),
		// Passed per-request, not read from .dev.vars, so the secret lives only
		// for the length of this run.
		"--var",
		`DEMO_MODE_SECRET:${secret}`,
		// The stranger in this journey has no browser token and no human to solve
		// a challenge. An empty secret is how the hook is told Turnstile is not
		// configured — the same state a fresh local checkout starts in.
		"--var",
		"TURNSTILE_SECRET_KEY:",
	],
	{ cwd: repo, stdio: "inherit" },
);

const stop = (signal) => {
	child.kill(signal);
	process.exit(0);
};
process.on("SIGTERM", () => stop("SIGTERM"));
process.on("SIGINT", () => stop("SIGINT"));
child.on("exit", (code) => process.exit(code ?? 0));
